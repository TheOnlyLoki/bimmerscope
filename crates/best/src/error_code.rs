#[allow(non_upper_case_globals)]
impl ErrorCode {
    pub const EDIABAS_IFH_LAST: ErrorCode = ErrorCode::EDIABAS_IFH_0049;
    pub const EDIABAS_BIP_LAST: ErrorCode = ErrorCode::EDIABAS_BIP_0029;
    pub const EDIABAS_SYS_LAST: ErrorCode = ErrorCode::EDIABAS_SYS_0029;
    pub const EDIABAS_API_LAST: ErrorCode = ErrorCode::EDIABAS_API_0029;
    pub const EDIABAS_NET_LAST: ErrorCode = ErrorCode::EDIABAS_NET_0049;
    pub const EDIABAS_IFH_LAST2: ErrorCode = ErrorCode::EDIABAS_IFH_0099;
    pub const EDIABAS_RUN_LAST: ErrorCode = ErrorCode::EDIABAS_RUN_0099;
    pub const EDIABAS_SEC_LAST: ErrorCode = ErrorCode::EDIABAS_SEC_0049;
    pub const EDIABAS_ERROR_LAST: ErrorCode = ErrorCode::EDIABAS_SEC_0049;

    /// C# `GetErrorDescription`: text for codes EDIABAS_IFH_0000..=EDIABAS_ERROR_LAST,
    /// empty string otherwise (including EDIABAS_ERR_NONE).
    pub fn description(self) -> &'static str {
        let code = self as u32;
        let first = ErrorCode::EDIABAS_IFH_0000 as u32;
        let last = ErrorCode::EDIABAS_ERROR_LAST as u32;
        if code < first || code > last {
            return "";
        }
        DESCRIPTIONS[(code - first) as usize]
    }

    /// Trap bit from C# `_trapBitDict`; 0 if the code has no entry (as in `SetError`).
    ///
    /// The C# dict adds BIP_0011, IFH_0069 and IFH_0074 only when the interface
    /// version is >= 760 / 770. This match returns them unconditionally.
    pub fn trap_bit(self) -> u32 {
        match self {
            ErrorCode::EDIABAS_BIP_0002 => 2,
            ErrorCode::EDIABAS_BIP_0006 => 6,
            ErrorCode::EDIABAS_BIP_0009 => 9,
            ErrorCode::EDIABAS_BIP_0010 => 10,
            ErrorCode::EDIABAS_IFH_0001 => 11,
            ErrorCode::EDIABAS_IFH_0002 => 12,
            ErrorCode::EDIABAS_IFH_0003 => 13,
            ErrorCode::EDIABAS_IFH_0004 => 14,
            ErrorCode::EDIABAS_IFH_0005 => 15,
            ErrorCode::EDIABAS_IFH_0006 => 16,
            ErrorCode::EDIABAS_IFH_0007 => 17,
            ErrorCode::EDIABAS_IFH_0008 => 18,
            ErrorCode::EDIABAS_IFH_0009 => 19,
            ErrorCode::EDIABAS_IFH_0010 => 20,
            ErrorCode::EDIABAS_IFH_0011 => 21,
            ErrorCode::EDIABAS_IFH_0012 => 22,
            ErrorCode::EDIABAS_IFH_0013 => 23,
            ErrorCode::EDIABAS_IFH_0014 => 24,
            ErrorCode::EDIABAS_IFH_0015 => 25,
            ErrorCode::EDIABAS_IFH_0016 => 26,
            ErrorCode::EDIABAS_BIP_0011 => 8, // version-gated in C#
            ErrorCode::EDIABAS_IFH_0069 => 28, // version-gated in C#
            ErrorCode::EDIABAS_IFH_0074 => 29, // version-gated in C#
            _ => 0,
        }
    }
}

